"""Turn ref/lander_ref.png (pixel-art lunar module) into src/10a_lander_data.js (the lander-specific,
hand-tuned version of tools/sprite2ascii.py: fixed 48 x 50 grid and a curated, named palette).

The reference is resampled onto its 48 x 50 pixel grid (block centres only, so the
anti-aliased seams between blocks are ignored) and every pixel is snapped to a small
fixed palette. The game draws the lander from this grid (see src/10a_lander_art.js).
"""
import os
import numpy as np
from PIL import Image

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # work from the repo root

SRC, OUT = 'ref/lander_ref.png', 'src/10a_lander_data.js'
X0, X1, Y0, Y1 = 154, 1100, 148, 1139       # bounding box of the drawing in the reference
NX, NY = 48, 50
# palette: (name, rgb, ink) - ink 0 marks outline colours, drawn as dark gaps rather than glyphs
PAL = [
    ('outline',     (19, 20, 28), 0),
    ('shadow',      (38, 39, 51), 0),
    ('gray-dark',   (66, 66, 78), 1),
    ('gray',        (100, 97, 110), 1),
    ('gray-mid',    (137, 135, 148), 1),
    ('gray-light',  (170, 167, 177), 1),
    ('silver',      (203, 200, 204), 1),
    ('white',       (232, 229, 227), 1),
    ('blue-dark',   (18, 56, 140), 1),
    ('blue',        (60, 130, 220), 1),
    ('brown',       (90, 46, 14), 1),
    ('orange-dark', (153, 71, 6), 1),
    ('orange',      (205, 110, 8), 1),
    ('orange-light', (242, 149, 14), 1),
    ('yellow',      (245, 190, 55), 1),
]
DIG = '0123456789abcdefghij'

a = np.array(Image.open(SRC).convert('RGBA')).astype(float)
pal = np.array([p[1] for p in PAL], float)
rows = []
for j in range(NY):
    row = ''
    for i in range(NX):
        xa, xb = X0 + (X1 - X0) * i / NX, X0 + (X1 - X0) * (i + 1) / NX
        ya, yb = Y0 + (Y1 - Y0) * j / NY, Y0 + (Y1 - Y0) * (j + 1) / NY
        blk = a[int(ya + (yb - ya) * .25):int(yb - (yb - ya) * .25), int(xa + (xb - xa) * .25):int(xb - (xb - xa) * .25)].reshape(-1, 4)
        w = blk[:, 3:4] / 255.
        if w.mean() < .5: row += '.'; continue
        col = (blk[:, :3] * w).sum(0) / max(w.sum(), 1e-6)
        row += DIG[int(np.argmin(((pal - col) ** 2).sum(1)))]
    rows.append(row)

with open(OUT, 'w') as f:
    f.write('// ===================== GAME · lander sprite (generated by tools/art.py from ref/lander_ref.png) =====================\n')
    f.write('// 48 x 50 pixels; "." is empty, every other character indexes LM_PAL. Origin (24, 28) is the centre of mass.\n')
    f.write('const LM_PAL = [\n' + ',\n'.join(f'  [{r}, {g}, {b}, {ink}]' for _, (r, g, b), ink in PAL) + '\n];\n')
    f.write('const LM_ROWS = [\n' + ',\n'.join(f"  '{r}'" for r in rows) + '\n];\n')
print('\n'.join(rows))
