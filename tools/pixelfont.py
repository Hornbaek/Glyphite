B32 = '0123456789abcdefghijklmnopqrstuv'


def rows(ch):
    top, _, desc = G[ch].partition('|')
    r = top.split() + (desc.split() if desc else ['.....', '.....'])
    assert len(r) == 9 and all(len(x) == 5 and set(x) <= set('#.') for x in r), ch
    return r


def packed():
    assert len(G) == 95 and all(chr(c) in G for c in range(32, 127))
    return ''.join(B32[int(row.replace('#', '1').replace('.', '0'), 2)] for c in range(32, 127) for row in rows(chr(c)))


def main():
    data = packed()
    p = ROOT / 'engine/05_render.js'
    s = p.read_text()
    s2 = re.sub(r"const FONT_DATA = '[0-9a-v]*';", f"const FONT_DATA = '{data}';", s)
    assert "const FONT_DATA = '" in s2, 'engine/05_render.js has no FONT_DATA line'
    if s2 != s: p.write_text(s2); print('wrote FONT_DATA into engine/05_render.js')
    else: print('FONT_DATA is up to date')
    if '--sheet' in sys.argv:
        from PIL import Image
        z, cw, ch = 4, 6, 12
        im = Image.new('RGB', (16 * cw * z, 6 * ch * z), (5, 7, 12))
        for c in range(32, 127):
            i = c - 32; gx, gy = (i % 16) * cw, (i // 16) * ch
            for y, row in enumerate(rows(chr(c))):
                for x, v in enumerate(row):
                    if v == '#':
                        for a in range(z):
                            for b in range(z): im.putpixel(((gx + x) * z + a, (gy + 2 + y) * z + b), (205, 214, 226))
        (ROOT / 'shots').mkdir(exist_ok=True); im.save(ROOT / 'shots/pixelfont.png'); print('wrote shots/pixelfont.png')


if __name__ == '__main__':
    main()
